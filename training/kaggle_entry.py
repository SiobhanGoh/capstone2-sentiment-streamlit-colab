"""Builds the single script Kaggle runs, embedding this commit's training code.

The GitHub workflow calls `python training/kaggle_entry.py <experiment> <commit> <out.py>`. Kaggle
script kernels upload one file, so the code travels inside it as a base64 tarball; the run is then
pinned to exactly that commit, whatever happens on the branch afterwards.
"""
import base64
import io
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIP = ["transformers==4.57.6", "huggingface_hub==0.36.2", "safetensors>=0.4.3", "sentencepiece>=0.2.0",
       "protobuf>=4.25", "scikit-learn==1.7.2"]

TEMPLATE = '''# Generated by training/kaggle_entry.py from commit {commit}; do not edit.
import base64, io, json, os, subprocess, sys, tarfile
EXPERIMENT, COMMIT = {experiment!r}, {commit!r}
archive = tarfile.open(fileobj=io.BytesIO(base64.b64decode({blob!r})), mode="r:gz")
try:
    archive.extractall("/tmp/src", filter="data")
except TypeError:  # Python without extraction filters; the archive is our own code
    archive.extractall("/tmp/src")
subprocess.run([sys.executable, "-m", "pip", "install", "-q", *{pip!r}], check=True)
os.makedirs("/kaggle/working/out", exist_ok=True)
import torch, transformers
json.dump({{"commit": COMMIT, "experiment": EXPERIMENT, "torch": torch.__version__,
           "transformers": transformers.__version__,
           "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None}},
          open("/kaggle/working/out/environment.json", "w"), indent=2)
subprocess.run([sys.executable, "-m", "training.kaggle_job", "--experiment", EXPERIMENT], cwd="/tmp/src", check=True)
'''


def bundle():
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        # The training code, plus the teacher choice for distillation once one exists (numbers only).
        extra = [ROOT / "training" / "distill_teacher.json"]
        for path in sorted((ROOT / "training").glob("*.py")) + [p for p in extra if p.exists()]:
            tar.add(path, arcname=f"training/{path.name}")
    return base64.b64encode(buf.getvalue()).decode()


def render(experiment, commit):
    from training.kaggle_job import EXPERIMENTS
    if experiment not in EXPERIMENTS:
        raise ValueError(f"Unknown experiment {experiment!r}.")
    return TEMPLATE.format(experiment=experiment, commit=commit, blob=bundle(), pip=PIP)


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    experiment, commit, out = sys.argv[1:4]
    Path(out).write_text(render(experiment, commit), encoding="utf-8")
